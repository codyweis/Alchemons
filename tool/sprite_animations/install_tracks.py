"""Write lib/models/costume_action_tracks.dart from the head tracks actions_build.py
recorded (actions/tracks_<family>.json), plus Darklet's hop."""
import sys, json, glob, os
S = sys.argv[1]
T = {}
for p in sorted(glob.glob(S + '/actions/tracks_*.json')):
    if len(os.path.basename(p).split('_')) != 2:       # a partial (ONLY=) run
        continue
    T.update(json.load(open(p)))
DARK = [315.0, 326.6, 347.6, 292.5, 283.1, 283.9, 283.9, 288.2, 331.3, 352.3, 303.4, 324.3, 310.3, 317.3, 315.0, 315.0]
T['LET15'] = {'hop': [[0, 0.0, round((y - 315) / 724, 4), 0.0] for y in DARK], 'sleep': [], 'fire': []}
out = ["part of 'celebration_costume.dart';", '',
       '// GENERATED by tool/sprite_animations/install_tracks.py — how each species\'',
       '// head moves through its hop, sleep and attack, for the costumes on it.', '//',
       '// By species, then action (hop, sleep, attack), then frame: the idle frame',
       '// the costume is fitted from, how far the point between the eyes has moved',
       '// from there (fractions of the frame) and how far the head has turned about',
       '// it (radians, clockwise).', '// dart format off',
       'const _actionTracks = <String, List<List<(int, double, double, double)>>>{']
for hid in sorted(T):
    out.append("  '%s': [" % hid)
    for name in ('hop', 'sleep', 'fire'):
        out.append('    [' + ', '.join('(%d, %s, %s, %s)' % (f[0], repr(float(f[1])), repr(float(f[2])), repr(float(f[3]))) for f in T[hid].get(name, [])) + '],')
    out.append('  ],')
out += ['};', '// dart format on', '']
open('lib/models/costume_action_tracks.dart', 'w').write('\n'.join(out))
print(len(T), 'species')
